#!/usr/bin/env node
// glance-explainer page upgrader. Zero dependencies, Node 18 or newer.
//   node upgrade.mjs <page.html | folder> [--dry-run] [--force]
// Brings an older explainer page up to the current template: its first <style> block and its first <script> block are
// replaced by the template's (read from ../assets/template.html), and the generator mark in <head> is set to the
// template's version. Content, extra <style> or <script> blocks the page added, and atlas <link>s stay as they are.
//   --dry-run  say what would happen, change nothing
//   --force    also upgrade a page whose blocks match no released version ("custom"); its own style edits are lost
// A backup <page>.html.bak is written first (.bak2, .bak3 when one exists). The checker runs on the result: if the
// original passed and the upgraded page does not, the original is put back and the backup is kept.
// Maintainers: after a release, add its entry to KNOWN with   node upgrade.mjs --hash <template at the tag>
import { readFileSync, writeFileSync, copyFileSync, existsSync, statSync, readdirSync, mkdtempSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

// Hash of the first <style> block plus the first <script> block (see blocksOf and hashOf), for every released
// template, first 16 hex digits of SHA-256, line endings read as LF. Generated by running this script's --hash on the
// template at each tag: before v1.4.0 that is `git show <tag>:assets/template.html`, from v1.4.0 it is
// `git show <tag>:skills/html-explainer/assets/template.html`, and from v2.0.0 `skills/glance-explainer/...`. When two releases shipped identical blocks, the
// earliest is listed. A page whose blocks match none of these (or the current template) is "custom".
const KNOWN = {
  '0804c10ae8c8c951': '1.0.0',
  '4b13de7db2854a31': '1.1.0',
  '2d2ccf9a23ee8306': '1.1.1',
  '588cf7cbc293e179': '1.2.0',
  'd71e0506754e3c2c': '1.3.0',
  '83e7648169e21f10': '1.4.0',
  'acae1e82fc72cdc3': '1.5.0',
  'f26b17219858845a': '1.6.0',
  '3d1647a21fdc5a3d': '1.7.0',
  'a289e76ebdc435d0': '1.8.0',
  'a44e96f9ad0659b3': '1.8.1',
  'c91f446872902d39': '1.9.0',
  '9dae902e0dda4c49': '1.9.1',
  '8fcaf88c539f8dcd': '2.0.0',
};

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const TEMPLATE = here('../assets/template.html'), CHECKER = here('./check.mjs');
const USAGE = 'usage: node upgrade.mjs <page.html | folder> [--dry-run] [--force]\n       node upgrade.mjs --hash <template.html>...   (maintainers: print the KNOWN hash of a template)';

// ---- finding things in a page (comments never count; a style or script body is read as one piece)
// The first <style> block and the first script that is code of the page: no src, and no type other than JavaScript.
function blocksOf(html) {
  const found = {};
  for (const m of html.matchAll(/<!--[\s\S]*?-->|<style\b[^>]*>[\s\S]*?<\/style\s*>|<script\b([^>]*)>[\s\S]*?<\/script\s*>/gi)) {
    const kind = m[0].startsWith('<!--') ? null : /^<style/i.test(m[0]) ? 'style' : 'script';
    if (!kind || found[kind]) continue;
    if (kind === 'script' && (/(?:^|\s)src\s*=/i.test(m[1]) || /\stype\s*=\s*["']?(?!(?:text|application)\/javascript|module)/i.test(' ' + m[1]))) continue;
    found[kind] = { text: m[0], start: m.index, end: m.index + m[0].length };
  }
  return found;
}
const hashOf = (b) => b.style && b.script
  ? createHash('sha256').update(`${b.style.text}\n${b.script.text}`.replace(/\r\n/g, '\n')).digest('hex').slice(0, 16) : null;

// an explainer page: <html data-type="..."> and the answer bar or a ballot card (same rule as hooks/explainer-check.mjs)
const looksLikeExplainer = (html) => /<html\b[^>]*\sdata-type\s*=/i.test(html) && (html.includes('class="answer"') || html.includes('class="ballot-card"'));

const mask = (html) => html.replace(/<!--[\s\S]*?-->/g, (c) => c.replace(/[^\r\n]/g, ' ')); // same length, comments blanked
// the generator mark: { start, end, version } or null; version is the number after "glance-explainer" (or "html-explainer", its name before 2.0.0), or '' for another tool's mark
function generatorOf(html) {
  for (const m of mask(html).matchAll(/<meta\b[^>]*>/gi)) {
    if (!/\sname\s*=\s*["']?generator\b/i.test(m[0])) continue;
    const content = /\scontent\s*=\s*"([^"]*)"|\scontent\s*=\s*'([^']*)'/i.exec(html.slice(m.index, m.index + m[0].length));
    const v = /^(?:glance|html)-explainer\s+(\S+)/i.exec((content?.[1] ?? content?.[2] ?? '').trim());
    return { start: m.index, end: m.index + m[0].length, version: v ? v[1] : '' };
  }
  return null;
}
// set the mark: replace ours, leave another tool's alone, or add one after the viewport meta (else charset, else <head>)
function withGenerator(html, version, eol) {
  const tag = `<meta name="generator" content="glance-explainer ${version}">`, g = generatorOf(html);
  if (g) return g.version ? html.slice(0, g.start) + tag + html.slice(g.end) : html;
  const masked = mask(html), head = masked.search(/<\/head\s*>/i), area = head < 0 ? masked : masked.slice(0, head);
  const after = [/<meta\b[^>]*\sname\s*=\s*["']?viewport\b[^>]*>/i, /<meta\b[^>]*\scharset\b[^>]*>/i, /<head\b[^>]*>/i].map((re) => re.exec(area)).find(Boolean);
  if (!after) return html;
  const at = after.index + after[0].length, lineStart = html.lastIndexOf('\n', after.index) + 1;
  const indent = /^[ \t]*$/.test(html.slice(lineStart, after.index)) ? html.slice(lineStart, after.index) : '';
  return html.slice(0, at) + eol + indent + tag + html.slice(at);
}

// ---- the current template
function readTemplate() {
  const html = readFileSync(TEMPLATE, 'utf8'), blocks = blocksOf(html), g = generatorOf(html);
  if (!blocks.style || !blocks.script || !g?.version) throw new Error(`${TEMPLATE} needs a <style> block, a <script> block and a generator mark`);
  return { blocks, hash: hashOf(blocks), version: g.version };
}

// ---- the checker
function check(file) {
  const r = spawnSync(process.execPath, [CHECKER, file, '--json'], { encoding: 'utf8', timeout: 30000, windowsHide: true, maxBuffer: 16 * 1024 * 1024 });
  try { const j = JSON.parse(r.stdout); return { ok: j.ok, fails: j.fails || [] }; } catch { return { ok: null, fails: [] }; } // null: the checker itself did not run
}

// ---- decide what a page needs: { say } when nothing changes, { html, from } when it does
function plan(html, tpl, force) {
  if (!looksLikeExplainer(html)) return { say: 'skipped: not an explainer page' };
  const blocks = blocksOf(html), hash = hashOf(blocks), g = generatorOf(html), mark = g?.version || null;
  const known = hash && KNOWN[hash], same = hash === tpl.hash;
  if (!known && !same && !force) return { say: 'skipped: custom styles (use --force)' };
  if (!blocks.style || !blocks.script) return { say: 'skipped: the page has no <style> or <script> block to replace' };
  if (same && mark === tpl.version) return { say: 'already current' };
  const eol = html.includes('\r\n') ? '\r\n' : '\n', fit = (s) => s.replace(/\r?\n/g, eol);
  let out = html;
  if (!same) { // later block first, so the earlier one keeps its offsets
    for (const k of ['style', 'script'].sort((a, b) => blocks[b].start - blocks[a].start))
      out = out.slice(0, blocks[k].start) + fit(tpl.blocks[k].text) + out.slice(blocks[k].end);
  }
  out = withGenerator(out, tpl.version, eol);
  if (out === html) return { say: 'already current' };
  return { html: out, from: known || (same ? mark || 'unknown' : 'custom'), markOnly: same };
}

// ---- one file
function upgradeFile(file, shown, tpl, opts) {
  let html;
  try { html = readFileSync(file, 'utf8'); } catch (e) { console.log(`${shown}: error: cannot read (${e.code || e.message})`); return 1; }
  const p = plan(html, tpl, opts.force);
  if (p.say) { console.log(`${shown}: ${p.say}`); return 0; }
  const before = check(file), line = p.markOnly ? `version mark set to ${tpl.version}` : `upgraded ${p.from} -> ${tpl.version}`; // markOnly: the blocks were current, only the mark was missing or stale
  if (opts.dry) { // judge the result without touching the page
    const dir = mkdtempSync(join(tmpdir(), 'glance-explainer-upgrade-'));
    try {
      const tmp = join(dir, basename(file)); writeFileSync(tmp, p.html);
      const after = check(tmp);
      console.log(`${shown}: ${before.ok && after.ok === false ? 'would restore: upgraded page fails the checker (nothing would change)' : `would be ${line}`}`);
    } finally { rmSync(dir, { recursive: true, force: true }); }
    return 0;
  }
  let bak = `${file}.bak`;
  for (let n = 2; existsSync(bak); n++) bak = `${file}.bak${n}`;
  try {
    copyFileSync(file, bak);
    writeFileSync(file, p.html);
  } catch (e) { console.log(`${shown}: error: cannot write (${e.code || e.message})`); return 1; }
  const after = check(file);
  if (before.ok && after.ok === false) {
    try { writeFileSync(file, html); } catch (e) { console.log(`${shown}: error: cannot put the original back (${e.code || e.message}); it is at ${bak}`); return 1; }
    console.log(`${shown}: restored: upgraded page fails the checker (backup kept: ${basename(bak)})`);
    for (const f of after.fails) console.log(`  FAIL  ${f}`);
    return 0;
  }
  console.log(`${shown}: ${line}`);
  if (before.ok === false && after.ok === false) console.log(`  note: the page failed the checker before the upgrade and still fails it (${after.fails.length} FAIL)`);
  return 0;
}

// ---- main
const args = process.argv.slice(2), flags = new Set(args.filter((a) => a.startsWith('--'))), paths = args.filter((a) => !a.startsWith('--'));
if ([...flags].some((f) => !['--dry-run', '--force', '--hash'].includes(f)) || !paths.length) { console.error(USAGE); process.exit(2); }

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((d) =>
  d.isDirectory() ? (d.name === 'node_modules' || d.name.startsWith('.') ? [] : walk(join(dir, d.name))) : /\.html$/i.test(d.name) ? [join(dir, d.name)] : []);

if (flags.has('--hash')) { // maintainers: print the KNOWN key of each template
  for (const f of paths) console.log(`${hashOf(blocksOf(readFileSync(f, 'utf8')))}  ${f}`);
} else {
  let tpl;
  try { tpl = readTemplate(); } catch (e) { console.error(`upgrade: ${e.message}`); process.exit(1); }
  let status = 0;
  for (const p of paths) {
    let files;
    try { files = statSync(p).isDirectory() ? walk(p) : [p]; } catch (e) { console.log(`${p}: error: cannot read (${e.code || e.message})`); status = 1; continue; }
    if (!files.length) console.log(`${p}: no .html files`);
    for (const f of files) status = Math.max(status, upgradeFile(resolve(f), f, tpl, { dry: flags.has('--dry-run'), force: flags.has('--force') }));
  }
  process.exitCode = status;
}
